from django.shortcuts import render
from core.db import get_collection, predictions_col, student_records_col
from core.decorators import role_required


def _student_live_metrics(request):
    user = request.session.get("user") or {}
    student_id = str(user.get("student_id") or "").strip()
    metrics = {
        "attendance": "N/A",
        "predicted_gpa": "Pending",
        "risk_level": "Pending",
        "courses": 0,
        "records_total": 0,
        "db_error": None,
    }
    try:
        metrics["courses"] = get_collection("courses").count_documents({"status": "ACTIVE"})
        metrics["records_total"] = student_records_col().count_documents({})
        if student_id:
            rec = student_records_col().find_one({"student_id": student_id}, {"_id": 0})
            if rec and rec.get("attendance_pct") is not None:
                metrics["attendance"] = f"{float(rec['attendance_pct']):.1f}%"
            pred = predictions_col().find_one({"student_id": student_id}, {"_id": 0})
            if pred:
                if pred.get("predicted_gpa") is not None:
                    metrics["predicted_gpa"] = f"{float(pred['predicted_gpa']):.2f}"
                metrics["risk_level"] = str(pred.get("risk_level") or "PENDING").upper()
    except Exception as exc:
        metrics["db_error"] = str(exc)
    return metrics


def _render_student_coming_soon(request, page_title, module_badge, module_description, module_icon, features):
    metrics = _student_live_metrics(request)
    risk_status = "danger" if metrics["risk_level"] == "HIGH" else ("warning" if metrics["risk_level"] == "MEDIUM" else "success")
    live_cards = [
        {
            "title": "Your Attendance",
            "value": metrics["attendance"],
            "badge": "Live student record",
            "status": "info",
            "icon": "fa-solid fa-calendar-check",
        },
        {
            "title": "Predicted GPA",
            "value": metrics["predicted_gpa"],
            "badge": "ML Ridge Forecast",
            "status": "success",
            "icon": "fa-solid fa-chart-line",
        },
        {
            "title": "Academic Standing",
            "value": metrics["risk_level"],
            "badge": "Dropout risk tier",
            "status": risk_status,
            "icon": "fa-solid fa-shield-halved",
        },
        {
            "title": "Active Courses",
            "value": metrics["courses"],
            "badge": f"{metrics['records_total']} total records",
            "status": "info",
            "icon": "fa-solid fa-book-open",
        },
    ]
    return render(
        request,
        "panels/coming_soon_panel.html",
        {
            "page_title": page_title,
            "active_role": "STUDENT",
            "module_badge": module_badge,
            "module_title": page_title,
            "module_description": module_description,
            "module_icon": module_icon,
            "roadmap_features": features,
            "features_pipe": "|".join(features),
            "live_cards": live_cards,
            "db_error": metrics["db_error"],
        },
    )


@role_required(["STUDENT"])
def student_dashboard(request):
    return _render_student_coming_soon(
        request,
        page_title="Learning Dashboard",
        module_badge="Student Portal · Coming Soon",
        module_description="Personalized attendance milestones, weekly LMS study targets, and AI-guided academic pacing insights.",
        module_icon="fa-solid fa-graduation-cap",
        features=[
            "Interactive attendance vs. target GPA progress tracker",
            "Weekly LMS engagement recommendations tailored to your courses",
            "Course-by-course assignment and internal marks breakdown",
            "Real-time faculty advisor notifications and support linkage",
        ],
    )


@role_required(["STUDENT"])
def student_report(request):
    return _render_student_coming_soon(
        request,
        page_title="Academic Report Card",
        module_badge="Student Portal · Coming Soon",
        module_description="Official semester forecast summary, historical GPA progression, and downloadable academic standing report.",
        module_icon="fa-solid fa-file-lines",
        features=[
            "Term-by-term predicted vs. achieved GPA comparison charts",
            "Subject-level credit summary and instructor remarks",
            "Early risk mitigation checklist generated by the ML engine",
            "Clean print-ready transcript and CSV record export",
        ],
    )
